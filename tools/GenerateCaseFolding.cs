// Writes src/EsfFormat/Internal/CaseFolding.Table.cs from the Unicode Character Database.
// Usage: dotnet run tools/GenerateCaseFolding.cs [unicode-version]

using System.Globalization;
using System.Text;

var version = args.Length > 0 ? args[0] : "17.0.0";
using var http = new HttpClient();
var data = await http.GetStringAsync($"https://www.unicode.org/Public/{version}/ucd/CaseFolding.txt");

var pairs = new List<(int From, int To)>();
foreach (var line in data.Split('\n'))
{
    var fields = line.Split('#')[0].Split(';');
    if (fields.Length < 3 || fields[1].Trim() is not ("C" or "S"))
    {
        continue;
    }
    pairs.Add((Hex(fields[0]), Hex(fields[2])));
}
pairs.Sort();

var output = new StringBuilder($$"""
    // <auto-generated>
    // Unicode {{version}} simple case folding (CaseFolding.txt, status C and S).
    // Regenerate with: dotnet run tools/GenerateCaseFolding.cs {{version}}
    // </auto-generated>

    namespace EveShipFit.EsfFormat.Internal;

    internal static partial class CaseFolding
    {
        private static ReadOnlySpan<int> From =>
        [

    """);
Rows(pairs.Select(p => p.From));
output.Append("""
        ];

        private static ReadOnlySpan<int> To =>
        [

    """);
Rows(pairs.Select(p => p.To));
output.Append("""
        ];
    }

    """);

var path = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(GetPath()))!, "../src/EsfFormat/Internal/CaseFolding.Table.cs");
File.WriteAllText(path, output.ToString());
Console.WriteLine($"{pairs.Count} mappings written to {Path.GetFullPath(path)}");

void Rows(IEnumerable<int> values)
{
    foreach (var row in values.Chunk(10))
    {
        output.Append("        ").AppendJoin(" ", row.Select(v => $"0x{v:X4},")).Append('\n');
    }
}

static int Hex(string s) => int.Parse(s.Trim(), NumberStyles.HexNumber, CultureInfo.InvariantCulture);

static string GetPath([System.Runtime.CompilerServices.CallerFilePath] string path = "") => path;
